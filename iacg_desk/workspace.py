"""One session <-> one folder. The mission workspace is the durable handoff a person can keep.

Layout of /data/iacg-work/<mission_id>/:
  *.tf, assumptions.md   the deliverable stack — explore main.tf, outputs.tf, variables.tf
  README.md              what this mission is, the locked target, how to resume
  work/                  what was FINALIZED and WHO did what (read-only provenance):
    ledger.json          every decision: value, origin (STATED/SOURCE/MUST_ASK), source, rationale
    build-sheet.json     the frozen scope + hash + who confirmed it
    evidence.json        validation results (tool + version + status + findings)
    acceptances.json     named human acceptances (who accepted what, why)
    repairs.json         bounded repair attempts
    manifest.json        session<->folder map + revision + resume hint

`package` syncs work/ from the live store and zips the whole folder (minus provider binaries) to
<data>/<mission_id>.zip, which the dashboard Files tab offers as a single download.
"""
from __future__ import annotations

import json
import zipfile
from pathlib import Path

from . import catalogue, ledger, versions
from .store import Store, now

EXCLUDE_DIRS = {".terraform", ".git", "__pycache__"}


def mission_tree(store: Store, mid: str) -> Path | None:
    mission = store.mission(mid)
    if mission is None:
        raise KeyError(f"unknown mission {mid}")
    tree = mission.get("tree")
    return Path(tree) if tree else None


def _manifest(store: Store, mid: str) -> dict:
    mission = store.mission(mid)
    sheet = store.sheet_get(mid) or {}
    return {
        "mission_id": mid,
        "title": mission["title"],
        "target": {"provider": mission["provider"], "iac_tool": mission["iac_tool"]},
        "target_locked": True,
        "target_note": "locked at creation; a different cloud/tool is a new mission, not an edit",
        "build_tier": mission["build_tier"],
        "state": mission["state"],
        "revision_id": sheet.get("revision_id"),
        "sheet_hash": sheet.get("sheet_hash"),
        "confirmed_by": sheet.get("confirmed_by"),
        "confirmed_at": sheet.get("confirmed_at"),
        "created_at": mission["created_at"],
        "updated_at": mission["updated_at"],
        "generated_at": now(),
        "layout": {"stack": "*.tf + assumptions.md at the folder root",
                   "work": "work/ — finalized decisions + who-did-what provenance (read-only)"},
        "resume": ("Read work/ledger.json + work/build-sheet.json to recover what was finalized and who "
                   "decided it. Change a decision and re-confirm to freeze a new revision; generation runs "
                   "only on the frozen revision."),
    }


def _readme(store: Store, mid: str, manifest: dict) -> str:
    m = manifest
    target = f"{m['target']['provider']} + {m['target']['iac_tool']}"
    rev = m["revision_id"] or "(not yet confirmed)"
    by = f" by {m['confirmed_by']}" if m["confirmed_by"] else ""
    return f"""# {m['title']}

IaC Genius mission `{mid}`. Target locked: **{target}** — a different cloud or IaC tool is a new
mission, not an edit. State: **{m['state']}**. Revision: `{rev}`{by}.

## What is in this folder

- `*.tf` — the generated stack. Start with `main.tf`; `outputs.tf` exports the values other stacks
  chain to; `variables.tf` holds the inputs (secrets are `sensitive`, `default = null`).
- `assumptions.md` — assumptions and open items that would change the design.
- `work/` — **what was finalized and who did what** (read-only provenance, kept separate from the code):
  - `ledger.json` — every decision with its origin: `STATED` (you said it), `SOURCE` (a disclosed
    platform default), or `MUST_ASK` (costly/irreversible, asked), plus the source and rationale.
  - `build-sheet.json` — the frozen scope, its one hash, and who confirmed it.
  - `evidence.json` — validation results: which tool ran, its version, and the status/findings.
  - `acceptances.json` — named human acceptances (who accepted which finding or the delivery, and why).
  - `repairs.json` — the bounded repair attempts spent.
  - `manifest.json` — this session's folder map and revision.

## Download

The whole folder is packaged as `{mid}.zip` (dashboard Files tab). Unzip it and explore offline.

## Resume or adjust next time

Keep this folder. A later session reads `work/ledger.json` + `work/build-sheet.json` to recover exactly
what was finalized and who decided it. Change a decision and re-confirm to freeze a new revision;
generation runs only on the frozen revision, so nothing drifts silently.

---
Generated by the IaC Genius CE desk. The model proposes; the toolchain decides. This stack was
validated, never applied — a person applies it elsewhere.
"""


def sync(store: Store, mid: str) -> dict | None:
    """Write the work/ provenance folder + README + manifest from the live store. No-op without a tree."""
    tree = mission_tree(store, mid)
    if tree is None:
        return None
    tree.mkdir(parents=True, exist_ok=True)
    work = tree / "work"
    work.mkdir(parents=True, exist_ok=True)
    manifest = _manifest(store, mid)
    evidence = {check: {k: row[k] for k in ("tool", "version", "status", "findings", "not_run_reason") if k in row}
                for check, row in store.latest_evidence(mid).items()}
    files = {
        work / "ledger.json": ledger.sorted_json(store, mid),
        work / "build-sheet.json": json.dumps(store.sheet_get(mid) or {"status": "unconfirmed"}, indent=2, sort_keys=True),
        work / "evidence.json": json.dumps(evidence, indent=2, sort_keys=True, default=str),
        work / "acceptances.json": json.dumps(store.acceptances(mid), indent=2, default=str),
        work / "repairs.json": json.dumps(store.repairs(mid), indent=2, default=str),
        work / "manifest.json": json.dumps(manifest, indent=2, sort_keys=True),
        tree / "README.md": _readme(store, mid, manifest),
    }
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
    return {"mission_id": mid, "tree": str(tree), "work_dir": str(work),
            "files": sorted(p.relative_to(tree).as_posix() for p in files)}


def package(store: Store, mid: str, out: str | None = None) -> dict:
    """Sync provenance, then zip the whole mission folder (minus provider binaries) for download."""
    tree = mission_tree(store, mid)
    if tree is None or not tree.is_dir():
        raise ValueError(f"mission {mid} has no generated tree yet; generate before packaging")
    sync(store, mid)
    zip_path = Path(out) if out else tree.parent / f"{mid}.zip"
    members = []
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in sorted(tree.rglob("*")):
            if not path.is_file():
                continue
            rel = path.relative_to(tree)
            if any(part in EXCLUDE_DIRS for part in rel.parts) or path.suffix == ".zip":
                continue
            zf.write(path, Path(mid) / rel)
            members.append(rel.as_posix())
    return {"mission_id": mid, "zip": str(zip_path), "bytes": zip_path.stat().st_size,
            "files": members, "download": f"dashboard Files tab -> {zip_path.name}"}